"""Parsers for the @coletrodriguez_ Following export and SetSmart CSV exports."""
import csv
import hashlib
import io
import json
import re
import zipfile
from pathlib import Path

from .handles import normalize

_HREF = re.compile(r'href="https?://(?:www\.)?instagram\.com/(?:_u/)?([^/"?]+)')
FOLLOWING_IN_ZIP = "connections/followers_and_following/following.html"


class ImportErrorReport(Exception):
    pass


def _handles_from_html(text):
    return [m.group(1) for m in _HREF.finditer(text)]


def _handles_from_json(text):
    data = json.loads(text)
    items = data.get("relationships_following", data) if isinstance(data, dict) else data
    out = []
    for it in items:
        for sld in it.get("string_list_data", []):
            if sld.get("value"):
                out.append(sld["value"])
            elif sld.get("href"):
                out += _handles_from_html(f'href="{sld["href"]}"')
        if it.get("title") and not it.get("string_list_data"):
            out.append(it["title"])
    return out


def parse_following(path):
    """Accepts the .txt (one handle per line), Instagram's following.html or
    following.json, or the whole data-download .zip. Returns (handles, info)."""
    p = Path(path)
    if not p.exists():
        raise ImportErrorReport(f"file not found: {path}")
    raw = p.read_bytes()
    sha = hashlib.sha256(raw).hexdigest()
    generated_by = generated_on = None
    try:
        if p.suffix.lower() == ".zip":
            with zipfile.ZipFile(io.BytesIO(raw)) as z:
                names = z.namelist()
                html = [n for n in names if n.endswith("followers_and_following/following.html")]
                js = [n for n in names if n.endswith("followers_and_following/following.json")]
                if html:
                    text = z.read(html[0]).decode("utf-8")
                    found = _handles_from_html(text)
                elif js:
                    found = _handles_from_json(z.read(js[0]).decode("utf-8"))
                else:
                    raise ImportErrorReport("zip has no followers_and_following/following.(html|json)")
                for n in names:
                    if n.endswith("message_1.html"):
                        t = re.sub(r"<[^>]+>", "\n", z.read(n).decode("utf-8", "replace"))
                        m = re.search(r"Generated by (\S+) on\s*\n+\s*([^\n]+)", t)
                        if m:
                            generated_by, generated_on = m.group(1), m.group(2).strip()
                        break
        else:
            text = raw.decode("utf-8-sig")
            if p.suffix.lower() in (".html", ".htm"):
                found = _handles_from_html(text)
            elif p.suffix.lower() == ".json":
                found = _handles_from_json(text)
            else:
                found = [ln for ln in text.splitlines() if ln.strip() and not ln.lstrip().startswith("#")]
    except (UnicodeDecodeError, json.JSONDecodeError, zipfile.BadZipFile, KeyError) as e:
        raise ImportErrorReport(f"parse error: {e}")
    handles, bad = set(), []
    for h in found:
        n = normalize(h)
        (handles.add(n) if n else bad.append(h))
    info = {"sha256": sha, "raw_entries": len(found), "unique": len(handles),
            "invalid": bad, "generated_by": generated_by, "generated_on": generated_on}
    return handles, info


def parse_setsmart_csv(path):
    """SetSmart export as CSV. Recognized columns (case-insensitive): a handle
    column (handle/username/instagram/ig_handle/contact) and optional
    account_id, status. Returns list of (handle, account_id, status)."""
    p = Path(path)
    if not p.exists():
        raise ImportErrorReport(f"file not found: {path}")
    with p.open(newline="", encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        if not reader.fieldnames:
            raise ImportErrorReport("CSV has no header row")
        cols = {c.lower().strip(): c for c in reader.fieldnames}
        hcol = next((cols[c] for c in ("handle", "username", "instagram", "ig_handle",
                                        "instagram_handle", "contact") if c in cols), None)
        if not hcol:
            raise ImportErrorReport(f"no handle column in {reader.fieldnames}")
        idcol = cols.get("account_id") or cols.get("instagram_id") or cols.get("ig_id")
        scol = cols.get("status")
        out, bad = [], 0
        for row in reader:
            h = normalize(row.get(hcol))
            if not h:
                bad += 1
                continue
            out.append((h, (row.get(idcol) or None) if idcol else None,
                        (row.get(scol) or "").strip().lower() if scol else ""))
    return out, bad
