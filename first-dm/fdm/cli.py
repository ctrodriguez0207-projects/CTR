def cmd_import_following(a):
    st = get_store()
    first = st.list_meta("other_following") is None
    try:
        handles, info = parse_following(a.file)
    except ImportErrorReport as e:
        print(f"ERROR importing Following export: {e}\nThe previous snapshot (if any) is unchanged.")
        return 2
    expect = a.expect if a.expect is not None else (EXPECTED_OTHER_FOLLOWING if first else None)
    if info["generated_by"] and normalize(info["generated_by"]) != OTHER_ACCOUNT:
        print(f"ERROR: export was generated by @{info['generated_by']}, expected @{OTHER_ACCOUNT}. Not imported.")
        return 2
    note = "count_verified" if expect is None or info["unique"] == expect else f"count_mismatch: expected {expect}, got {info['unique']}"
    st.replace_list("other_following", [(h, None) for h in sorted(handles)], str(Path(a.file).name),
                    exported_at=info["generated_on"], sha256=info["sha256"], note=note)
    print(f"Imported @{OTHER_ACCOUNT} Following export: {info['raw_entries']} entries, {info['unique']} unique handles")
    if info["generated_by"]:
        print(f"  export generated by @{info['generated_by']} on {info['generated_on']}")
    if info["invalid"]:
        print(f"  {len(info['invalid'])} entries were not valid handles and were ignored: {info['invalid'][:5]}")
    if note != "count_verified":
        print(f"  BLOCKER: {note}. Live sending stays disabled until this is resolved.")
    _after_list_change(st)
    return 0 if note == "count_verified" else 3


def cmd_personal(a):
    st = get_store()
    if a.action == "list":
        for r in st.db.execute("SELECT handle FROM list_entries WHERE list_name='personal_dnc' ORDER BY handle"):
            print(r["handle"])
        print(f"({st.list_count('personal_dnc')} handles)", file=sys.stderr)
        return 0
    raw = list(a.handles)
    if a.file:
        raw += Path(a.file).read_text().splitlines()
    good = [normalize(h) for h in raw if h.strip()]
    bad = [h for h, n in zip([h for h in raw if h.strip()], good) if not n]
    good = [g for g in good if g]
    if bad:
        print("Ignored (not valid handles):", bad)
    if a.action == "add":
        n = st.add_to_list("personal_dnc", good, "cli")
        print(f"Added {n} new handle(s). Personal list now has {st.list_count('personal_dnc')}.")
    else:
        n = st.remove_from_list("personal_dnc", good)
        print(f"Removed {n}. Personal list now has {st.list_count('personal_dnc')}.")
    _after_list_change(st)
    return 0


def cmd_setsmart(a):
    st = get_store()
    try:
        rows, bad = parse_setsmart_csv(a.file)
    except ImportErrorReport as e:
        print(f"ERROR importing SetSmart export: {e}. Previous list unchanged; sending will pause if it goes stale.")
        return 2
    exported = a.exported_at or datetime.fromtimestamp(Path(a.file).stat().st_mtime, timezone.utc).isoformat()
    exported_dt = datetime.fromisoformat(exported)
    if exported_dt.tzinfo is None:
        exported_dt = exported_dt.replace(tzinfo=ET)
    name = "setsmart_dnc" if a.kind == "dnc" else "setsmart_history"
    if a.kind == "history":
        # Everyone with any outreach record or a queued first message is excluded.
        counts = Counter(s or "(no status)" for _, _, s in rows)
        print("SetSmart history statuses:", dict(counts))
    st.replace_list(name, [(h, aid) for h, aid, _ in rows], Path(a.file).name,
                    exported_at=exported_dt.astimezone(timezone.utc).isoformat())
    print(f"Imported SetSmart {a.kind}: {st.list_count(name)} unique handles ({bad} rows without a valid handle), "
          f"exported {exported_dt.astimezone(ET):%Y-%m-%d %I:%M %p %Z}")
    _after_list_change(st)
    return 0


def cmd_status(a):
    st = get_store()
    ig = get_ig()
    p, why = is_paused(st, PAUSE_FILE)
    print(f"Mode: {st.get('mode')}   Sending: {'PAUSED — ' + why if p else 'active'}")
    print(f"Next opener: #{int(st.get('rotation_pos')) % 4 + 1} (rotation position {st.get('rotation_pos')})")
    print("\nRequired checks:")
    for name, desc, ok, detail in requirement_status(st, ig):
        print(f"  [{'OK ' if ok else 'NO '}] {desc}\n         {detail}")
    c = Counter(r["status"] for r in st.db.execute("SELECT status FROM candidates"))
    print("\nCandidates:", dict(c) or "none yet")
    return 0


def cmd_pause(a):
    st = get_store()
    PAUSE_FILE.parent.mkdir(parents=True, exist_ok=True)
    PAUSE_FILE.write_text(a.reason + "\n")
    pause(st, "paused by Cole: " + a.reason)
    print("Paused. No further DM will be attempted until you run: python3 -m fdm resume")
    return 0


def cmd_resume(a):
    st = get_store()
    bl = blockers(st, get_ig())
    if st.get("mode") != "live":
        print("Not in live mode; nothing to resume. (Use enable-live after approving a dry run.)")
        return 1
    if bl:
        print("Cannot resume; required checks unavailable:")
        for n, d in bl:
            print(f"  - {n}: {d}")
        return 1
    PAUSE_FILE.unlink(missing_ok=True)
    st.set("paused", "0")
    st.set("pause_reason", "")
    st.set("consecutive_unconfirmed", "0")
    st.event("resumed")
    print("Resumed. Sending continues within the window, caps and 3-minute spacing (no catch-up).")
    return 0


def cmd_dry_run(a):
    from .report import dry_run_report
    st = get_store()
    text, rid = dry_run_report(st, get_ig())
    out = DATA / "reports" / f"dry-run-{rid}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    st.set("last_dry_run_id", rid)
    st.set("last_dry_run_at", datetime.now(timezone.utc).isoformat())
    print(text)
    print(f"\nSaved: {out}\nDry-run ID: {rid}")
    return 0


def cmd_enable_live(a):
    st = get_store()
    ig = get_ig()
    problems = []
    if a.approve != st.get("last_dry_run_id"):
        problems.append("approval ID does not match the latest dry run (run dry-run, review it, then approve that ID)")
    for n, d in blockers(st, ig):
        problems.append(f"{n}: {d}")
    if getattr(ig, "is_test_data", False):
        problems.append("Instagram adapter is test data")
    if problems:
        print("Live sending NOT enabled:")
        for p in problems:
            print("  -", p)
        return 1
    st.set("mode", "live")
    st.set("approved_dry_run_id", a.approve)
    st.set("paused", "0")
    st.set("pause_reason", "")
    PAUSE_FILE.unlink(missing_ok=True)
    st.event("live_enabled", dry_run_id=a.approve)
    print("Live sending enabled. Start the sender with: python3 -m fdm run")
    return 0


def cmd_run(a):
    st = get_store()
    DATA.mkdir(parents=True, exist_ok=True)
    lock = open(DATA / "sender.lock", "w")
    try:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        print("Another sender is already running. Only one sender may be active.")
        return 1
    ig = get_ig()
    n = recover_pending(st)
    if n:
        print(f"Marked {n} interrupted attempt(s) as uncertain; they will not be retried.")
    last_poll = 0
    while True:
        if time.time() - last_poll > 600:
            try:
                poll_reels(st, ig)
            except Exception as e:  # noqa: BLE001
                if st.get("mode") == "live":
                    pause(st, f"cannot monitor Reels: {e}")
            last_poll = time.time()
        r = send_one(st, ig, pause_file=PAUSE_FILE)
        print(f"{to_et(utcnow()):%Y-%m-%d %I:%M:%S %p %Z}  {r}", flush=True)
        if a.once:
            return 0
        time.sleep(60)


def cmd_summary(a):
    st = get_store()
    day = a.date or to_et(utcnow()).date().isoformat()
    rows = [r for r in st.db.execute("SELECT * FROM attempts ORDER BY id") if r["ts_et"][:10] == day]
    c = Counter(r["outcome"] for r in rows)
    skips = Counter()
    for r in st.db.execute("SELECT checked_at, reason FROM candidates WHERE status='skipped'"):
        if to_et(datetime.fromisoformat(r["checked_at"])).date().isoformat() == day:
            skips[r["reason"]] += 1
    p, why = is_paused(st, PAUSE_FILE)
    lines = [f"# First-DM summary for {day} (Eastern)", "",
             f"- Mode: {st.get('mode')}; sending is {'PAUSED (' + why + ')' if p else 'active'}",
             f"- Confirmed sends: {c['sent']}", f"- Uncertain attempts: {c['uncertain']}",
             f"- Other outcomes: {dict((k, v) for k, v in c.items() if k not in ('sent', 'uncertain')) or 'none'}",
             f"- Attempts counted toward caps: {len(rows)} / {DAILY_CAP} daily (max {HOURLY_CAP} per hour)",
             f"- Skips by reason: {dict(skips) or 'none'}", "", "## Attempt log", "",
             "| Time (ET) | Recipient | Source Reel | Opener | Message | Outcome |", "|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['ts_et'][11:19]} | @{r['handle']} | {r['source_reel']} | {r['opener']} | {r['message']} | {r['outcome']}{' — ' + r['detail'] if r['detail'] else ''} |")
    text = "\n".join(lines)
    out = DATA / "summaries" / f"{day}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(text)
    return 0


def cmd_config(a):
    st = get_store()
    if a.setsmart_max_age_hours is not None:
        st.set("setsmart_max_age_hours", a.setsmart_max_age_hours)
        print(f"SetSmart lists must be at most {a.setsmart_max_age_hours} h old.")
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(prog="python3 -m fdm", description=f"First-DM workflow for @{SENDER}")
    sp = ap.add_subparsers(dest="cmd", required=True)
    sp.add_parser("status").set_defaults(f=cmd_status)
    p = sp.add_parser("import-following", help=f"load/replace the @{OTHER_ACCOUNT} Following export (.txt/.html/.json/.zip)")
    p.add_argument("file")
    p.add_argument("--expect", type=int, help="expected unique handles (default 362 on first import)")
    p.set_defaults(f=cmd_import_following)
    p = sp.add_parser("personal", help="personal do-not-contact list")
    p.add_argument("action", choices=["add", "remove", "list"])
    p.add_argument("handles", nargs="*")
    p.add_argument("--file")
    p.set_defaults(f=cmd_personal)
    p = sp.add_parser("setsmart", help="import a SetSmart CSV export")
    p.add_argument("kind", choices=["dnc", "history"])
    p.add_argument("file")
    p.add_argument("--exported-at", help="when you exported it, e.g. 2026-11-13T09:30-05:00 (default: file time)")
    p.set_defaults(f=cmd_setsmart)
    sp.add_parser("dry-run").set_defaults(f=cmd_dry_run)
    p = sp.add_parser("enable-live")
    p.add_argument("--approve", required=True, metavar="DRY_RUN_ID")
    p.set_defaults(f=cmd_enable_live)
    p = sp.add_parser("pause")
    p.add_argument("reason", nargs="?", default="manual pause")
    p.set_defaults(f=cmd_pause)
    sp.add_parser("resume").set_defaults(f=cmd_resume)
    p = sp.add_parser("run", help="start the single sender loop")
    p.add_argument("--once", action="store_true")
    p.set_defaults(f=cmd_run)
    p = sp.add_parser("summary")
    p.add_argument("--date", help="YYYY-MM-DD (Eastern); default today")
    p.set_defaults(f=cmd_summary)
    p = sp.add_parser("config")
    p.add_argument("--setsmart-max-age-hours", type=float)
    p.set_defaults(f=cmd_config)
    a = ap.parse_args(argv)
    return a.f(a)
