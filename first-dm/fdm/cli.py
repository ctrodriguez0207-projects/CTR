DATA = Path(os.environ.get("FDM_DATA", Path(__file__).resolve().parent.parent / "data"))
PAUSE_FILE = DATA / "PAUSE"

NO_IG_WHY = "no verified Instagram access (see note below the table)"
NO_IG_NOTE = ("Instagram's official messaging API only lets @colethomasrod message people who messaged it "
              "first, and it does not expose Reel likers or who the account follows. Driving the signed-in "
              "app or website with automation is against Instagram's terms. Nothing here is signed into Instagram.")


def get_store():
    DATA.mkdir(parents=True, exist_ok=True)
    return Store(str(DATA / "state.db"))


def get_ig():
    cfg = DATA / "config.json"
    name = json.loads(cfg.read_text()).get("instagram_adapter", "none") if cfg.exists() else "none"
    if name != "none":
        print(f"! unknown instagram_adapter '{name}' in config.json; treating Instagram as unavailable")
    return NoInstagramAccess(NO_IG_WHY)


def _after_list_change(st):
    s = recheck_queue(st, get_ig())
    if s:
        print("Rechecked queued candidates:", dict(s))


