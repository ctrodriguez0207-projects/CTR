def cmd_import_following(a):
    st = get_store()
    first = st.list_meta("other_following") is None
    try:
        handles, info = parse_following(a.file)
    except ImportErrorReport as e:
        print(f"ERROR importing Following export: {e}\nThe previous snapshot (if any) is unchanged.")
        return 2
    expect = a.expect if a.expect is not None else (EXPECTED_OTHER_FOLLOWING if first else None)
    if info["generated_by"] and normalize(info["generated_by"]) != OTHER_ACCOUNT:
        print(f"ERROR: export was generated by @{info['generated_by']}, expected @{OTHER_ACCOUNT}. Not imported.")
        return 2
    note = "count_verified" if expect is None or info["unique"] == expect else f"count_mismatch: expected {expect}, got {info['unique']}"
    st.replace_list("other_following", [(h, None) for h in sorted(handles)], str(Path(a.file).name),
                    exported_at=info["generated_on"], sha256=info["sha256"], note=note)
    print(f"Imported @{OTHER_ACCOUNT} Following export: {info['raw_entries']} entries, {info['unique']} unique handles")
    if info["generated_by"]:
        print(f"  export generated by @{info['generated_by']} on {info['generated_on']}")
    if info["invalid"]:
        print(f"  {len(info['invalid'])} entries were not valid handles and were ignored: {info['invalid'][:5]}")
    if note != "count_verified":
        print(f"  BLOCKER: {note}. Live sending stays disabled until this is resolved.")
    _after_list_change(st)
    return 0 if note == "count_verified" else 3


def cmd_personal(a):
    st = get_store()
    if a.action == "list":
        for r in st.db.execute("SELECT handle FROM list_entries WHERE list_name='personal_dnc' ORDER BY handle"):
            print(r["handle"])
        print(f"({st.list_count('personal_dnc')} handles)", file=sys.stderr)
        return 0
    raw = list(a.handles)
    if a.file:
        raw += Path(a.file).read_text().splitlines()
    good = [normalize(h) for h in raw if h.strip()]
    bad = [h for h, n in zip([h for h in raw if h.strip()], good) if not n]
    good = [g for g in good if g]
    if bad:
        print("Ignored (not valid handles):", bad)
    if a.action == "add":
        n = st.add_to_list("personal_dnc", good, "cli")
        print(f"Added {n} new handle(s). Personal list now has {st.list_count('personal_dnc')}.")
    else:
        n = st.remove_from_list("personal_dnc", good)
        print(f"Removed {n}. Personal list now has {st.list_count('personal_dnc')}.")
    _after_list_change(st)
    return 0


def cmd_setsmart(a):
    st = get_store()
    try:
        rows, bad = parse_setsmart_csv(a.file)
    except ImportErrorReport as e:
        print(f"ERROR importing SetSmart export: {e}. Previous list unchanged; sending will pause if it goes stale.")
        return 2
    exported = a.exported_at or datetime.fromtimestamp(Path(a.file).stat().st_mtime, timezone.utc).isoformat()
    exported_dt = datetime.fromisoformat(exported)
    if exported_dt.tzinfo is None:
        exported_dt = exported_dt.replace(tzinfo=ET)
    name = "setsmart_dnc" if a.kind == "dnc" else "setsmart_history"
    if a.kind == "history":
        # Everyone with any outreach record or a queued first message is excluded.
        counts = Counter(s or "(no status)" for _, _, s in rows)
        print("SetSmart history statuses:", dict(counts))
    st.replace_list(name, [(h, aid) for h, aid, _ in rows], Path(a.file).name,
                    exported_at=exported_dt.astimezone(timezone.utc).isoformat())
    print(f"Imported SetSmart {a.kind}: {st.list_count(name)} unique handles ({bad} rows without a valid handle), "
          f"exported {exported_dt.astimezone(ET):%Y-%m-%d %I:%M %p %Z}")
    _after_list_change(st)
    return 0


def cmd_likers(a):
    st = get_store()
    rid = parse_reel_id(a.reel)
    lines = list(a.handles)
    if a.file:
        lines += Path(a.file).read_text().splitlines()
    if not a.file and not a.handles:
        print("Paste the Reel's visible likers, one handle per line. Finish with an empty line (or Ctrl-D):")
        try:
            while True:
                ln = input()
                if not ln.strip():
                    break
                lines.append(ln)
        except EOFError:
            pass
    handles, ignored = parse_liker_lines(lines)
    first = st.db.execute("SELECT 1 FROM reels WHERE reel_id=?", (rid,)).fetchone() is None
    stats = ingest_likers(st, get_ig(), rid, [(h, None) for h in handles])
    if first:
        print(f"Reel {rid}: first look, so {stats['baseline_likers']} existing likers were recorded as the baseline. Nobody was queued.")
    else:
        q = stats.get("queued", 0)
        sk = {k[8:]: v for k, v in stats.items() if k.startswith("skipped:")}
        print(f"Reel {rid}: {stats.get('new_likes', 0)} new likers, {q} queued, "
              f"{stats.get('duplicate_person', 0)} already known from another Reel, skipped: {sk or 'none'}")
    if ignored:
        print(f"Ignored {len(ignored)} lines that aren't handles (names/buttons): {ignored[:6]}{' ...' if len(ignored) > 6 else ''}")
    return 0


def _ask(prompt, choices):
    while True:
        ans = input(f"{prompt} [{'/'.join(choices)}] ").strip().lower()
        if ans in choices:
            return ans


YN = {"y": True, "n": False, "?": None}


def _resolve_pending(st):
    for a in pending_attempts(st):
        print(f"\nUnfinished attempt from {a['ts_et'][:16].replace('T', ' ')} ET to @{a['handle']}:")
        print(f"  \"{a['message']}\"")
        r = _ask("Did this message appear in their conversation? y = sent, u = unsure, n = I didn't send it, "
                 "w = Instagram showed a warning/block/challenge", ["y", "u", "n", "w"])
        out = assist_result(st, a["id"], {"y": "sent", "u": "uncertain", "n": "not_sent", "w": "warning"}[r])
        print(f"  Recorded: {out}. @{a['handle']} will never be messaged again by this workflow.")


def cmd_assist(a):
    st = get_store()
    if not getattr(get_ig(), "manual", False):
        print("assist needs the manual Instagram adapter (config.json instagram_adapter = manual).")
        return 1
    _resolve_pending(st)
    while True:
        r = assist_next(st, pause_file=PAUSE_FILE)
        if r[0] is None:
            msg = r[1]
            if msg.startswith("wait"):
                t = next_allowed_at(st)
                msg += f" — next attempt allowed at {to_et(t):%I:%M %p %Z on %a %b %d}" if t else ""
            print("\n" + msg)
            break
        c, opener, text = r
        print(f"\nNext: @{c['handle']}  (liked Reel {c['source_reel']})   https://www.instagram.com/{c['handle']}/")
        print("All list checks passed (other account's Following, personal list, SetSmart DNC + history, this workflow's log).")
        print("On Instagram, signed in as you, check:")
        ans = {}
        ans["signed_in_as_sender"] = YN[_ask("  Are you signed into @colethomasrod right now?", ["y", "n"])]
        if not ans["signed_in_as_sender"]:
            assist_reserve(st, c["id"], ans, pause_file=PAUSE_FILE)
            print("Paused: wrong or unconfirmed account. Switch to @colethomasrod, then run: python3 -m fdm resume")
            return 1
        ans["intended_recipient"] = YN[_ask(f"  Is https://www.instagram.com/{c['handle']}/ the person who liked your Reel? (? = can't tell)", ["y", "n", "?"])]
        ans["follows"] = YN[_ask("  Do YOU follow them? (their profile button says Following)", ["y", "n", "?"])]
        ans["dm_thread"] = YN[_ask("  Is there ANY existing DM conversation with them (inbox, requests, hidden)?", ["y", "n", "?"])]
        ans["can_message"] = YN[_ask("  Does Instagram let you message them (Message works, no restriction)?", ["y", "n", "?"])]
        res = assist_reserve(st, c["id"], ans, pause_file=PAUSE_FILE)
        if res[0] != "reserved":
            print(f"Not messaging @{c['handle']}: {res[1]}")
            if res[0] in ("paused", "wait"):
                break
            continue
        _, aid, opener, text = res
        print(f"\nReserved and counted. Send this exact message (opener #{opener}) to @{c['handle']}:\n\n    {text}\n")
        out = _ask("Did it appear in @" + c["handle"] + "'s conversation? y = sent, u = unsure, n = I didn't send it, "
                   "w = Instagram showed a warning/block/challenge", ["y", "u", "n", "w"])
        final = assist_result(st, aid, {"y": "sent", "u": "uncertain", "n": "not_sent", "w": "warning"}[out])
        print(f"Recorded: {final}.")
        if a.once:
            break
    today = to_et(utcnow()).date().isoformat()
    rows = [r for r in st.db.execute("SELECT outcome, ts_et FROM attempts") if r["ts_et"][:10] == today]
    c = Counter(r["outcome"] for r in rows)
    print(f"Today: {c['sent']} confirmed, {c['uncertain']} uncertain, {c['not_sent']} not sent; "
          f"{len(rows)}/{DAILY_CAP} attempts used.")
    return 0


def cmd_step(a):
    """Non-interactive assist, one stage at a time (for driving from chat)."""
    st = get_store()
    if a.stage == "next":
        pend = pending_attempts(st)
        if pend:
            for p in pend:
                print(f"PENDING attempt {p['id']} to @{p['handle']}: \"{p['message']}\" — report it with: step result {p['id']} y|u|n|w")
            return 0
        r = assist_next(st, pause_file=PAUSE_FILE)
        if r[0] is None:
            print(r[1])
            return 0
        c, opener, text = r
        print(f"candidate {c['id']}: @{c['handle']} (Reel {c['source_reel']}) https://www.instagram.com/{c['handle']}/ "
              f"— would get opener #{opener}: \"{text}\"")
        print("Confirm: signed in as @colethomasrod? right profile? you follow them? any DM thread? can message?")
        return 0
    if a.stage == "confirm":
        vals = [YN[v] for v in a.args[1:6]] if len(a.args) == 6 and all(v in YN for v in a.args[1:6]) else None
        if not vals:
            print("usage: step confirm CANDIDATE_ID signed_in profile follows thread can_message   (each y/n/?)")
            return 2
        keys = ["signed_in_as_sender", "intended_recipient", "follows", "dm_thread", "can_message"]
        res = assist_reserve(st, int(a.args[0]), dict(zip(keys, vals)), pause_file=PAUSE_FILE)
        if res[0] == "reserved":
            print(f"RESERVED attempt {res[1]} (counted). Send this exact message, opener #{res[2]}:\n{res[3]}")
        else:
            print(f"{res[0]}: {res[1]}")
        return 0
    if a.stage == "result":
        if len(a.args) != 2 or a.args[1] not in ("y", "u", "n", "w"):
            print("usage: step result ATTEMPT_ID y|u|n|w")
            return 2
        out = assist_result(st, int(a.args[0]), {"y": "sent", "u": "uncertain", "n": "not_sent", "w": "warning"}[a.args[1]])
        print(f"Recorded: {out}")
        return 0


def cmd_status(a):
    st = get_store()
    ig = get_ig()
    p, why = is_paused(st, PAUSE_FILE)
    print(f"Mode: {st.get('mode')}   Sending: {'PAUSED — ' + why if p else 'active'}")
    print(f"Next opener: #{int(st.get('rotation_pos')) % 4 + 1} (rotation position {st.get('rotation_pos')})")
    print("\nRequired checks:")
    for name, desc, ok, detail in requirement_status(st, ig):
        print(f"  [{('N/A' if detail.startswith('NOT REQUIRED') else 'YOU' if 'Cole' in detail else 'OK ') if ok else 'NO '}] {desc}\n         {detail}")
    c = Counter(r["status"] for r in st.db.execute("SELECT status FROM candidates"))
    print("\nCandidates:", dict(c) or "none yet")
    pend = pending_attempts(st)
    if pend:
        print(f"Unfinished attempts waiting for your answer: {len(pend)} (run: python3 -m fdm assist)")
    t = next_allowed_at(st, utcnow() - timedelta(minutes=1))
    if t:
        print(f"Schedule allows the next attempt at {to_et(t):%I:%M %p %Z, %a %b %d}")
    return 0


def cmd_pause(a):
    st = get_store()
    PAUSE_FILE.parent.mkdir(parents=True, exist_ok=True)
    PAUSE_FILE.write_text(a.reason + "\n")
    pause(st, "paused by Cole: " + a.reason)
    print("Paused. No further DM will be attempted until you run: python3 -m fdm resume")
    return 0


def cmd_resume(a):
    st = get_store()
    bl = blockers(st, get_ig())
    if st.get("mode") != "live":
        print("Not in live mode; nothing to resume. (Use enable-live after approving a dry run.)")
        return 1
    if bl:
        print("Cannot resume; required checks unavailable:")
        for n, d in bl:
            print(f"  - {n}: {d}")
        return 1
    PAUSE_FILE.unlink(missing_ok=True)
    st.set("paused", "0")
    st.set("pause_reason", "")
    st.set("consecutive_unconfirmed", "0")
    st.event("resumed")
    print("Resumed. Sending continues within the window, caps and 3-minute spacing (no catch-up).")
    return 0


