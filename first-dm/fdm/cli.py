def cmd_enable_live(a):
    st = get_store()
    ig = get_ig()
    problems = []
    if a.approve != st.get("last_dry_run_id"):
        problems.append("approval ID does not match the latest dry run (run dry-run, review it, then approve that ID)")
    for n, d in blockers(st, ig):
        problems.append(f"{n}: {d}")
    if getattr(ig, "is_test_data", False):
        problems.append("Instagram adapter is test data")
    if problems:
        print("Live sending NOT enabled:")
        for p in problems:
            print("  -", p)
        return 1
    st.set("mode", "live")
    st.set("approved_dry_run_id", a.approve)
    st.set("paused", "0")
    st.set("pause_reason", "")
    PAUSE_FILE.unlink(missing_ok=True)
    st.event("live_enabled", dry_run_id=a.approve)
    print("Live sending enabled. Send with: python3 -m fdm assist")
    return 0


def cmd_run(a):
    st = get_store()
    DATA.mkdir(parents=True, exist_ok=True)
    lock = open(DATA / "sender.lock", "w")
    try:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
    except BlockingIOError:
        print("Another sender is already running. Only one sender may be active.")
        return 1
    ig = get_ig()
    if getattr(ig, "manual", False):
        print("Automatic sending isn't available (no supported Instagram integration). Use: python3 -m fdm assist")
        return 1
    n = recover_pending(st)
    if n:
        print(f"Marked {n} interrupted attempt(s) as uncertain; they will not be retried.")
    last_poll = 0
    while True:
        if time.time() - last_poll > 600:
            try:
                poll_reels(st, ig)
            except Exception as e:  # noqa: BLE001
                if st.get("mode") == "live":
                    pause(st, f"cannot monitor Reels: {e}")
            last_poll = time.time()
        r = send_one(st, ig, pause_file=PAUSE_FILE)
        print(f"{to_et(utcnow()):%Y-%m-%d %I:%M:%S %p %Z}  {r}", flush=True)
        if a.once:
            return 0
        time.sleep(60)


def cmd_summary(a):
    st = get_store()
    day = a.date or to_et(utcnow()).date().isoformat()
    rows = [r for r in st.db.execute("SELECT * FROM attempts ORDER BY id") if r["ts_et"][:10] == day]
    c = Counter(r["outcome"] for r in rows)
    skips = Counter()
    for r in st.db.execute("SELECT checked_at, reason FROM candidates WHERE status='skipped'"):
        if to_et(datetime.fromisoformat(r["checked_at"])).date().isoformat() == day:
            skips[r["reason"]] += 1
    p, why = is_paused(st, PAUSE_FILE)
    lines = [f"# First-DM summary for {day} (Eastern)", "",
             f"- Mode: {st.get('mode')}; sending is {'PAUSED (' + why + ')' if p else 'active'}",
             *([f"- SetSmart checks: not used ({st.get('setsmart_dropped_reason')})"] if st.get("setsmart_required") == "0" else []),
             f"- Confirmed sends: {c['sent']}", f"- Uncertain attempts: {c['uncertain']}", f"- Reserved but not sent by Cole: {c['not_sent']}",
             f"- Waiting for Cole's answer: {c['pending']}",
             f"- Other outcomes: {dict((k, v) for k, v in c.items() if k not in ('sent', 'uncertain', 'not_sent', 'pending')) or 'none'}",
             f"- Attempts counted toward caps: {len(rows)} / {DAILY_CAP} daily (max {HOURLY_CAP} per hour)",
             f"- Skips by reason: {dict(skips) or 'none'}", "", "## Attempt log", "",
             "| Time (ET) | Recipient | Source Reel | Opener | Message | Outcome |", "|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['ts_et'][11:19]} | @{r['handle']} | {r['source_reel']} | {r['opener']} | {r['message']} | {r['outcome']}{_note(r['detail'])} |")
    text = "\n".join(lines)
    out = DATA / "summaries" / f"{day}.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(text)
    return 0


def _note(detail):
    if not detail:
        return ""
    try:
        n = json.loads(detail).get("note")
    except ValueError:
        n = detail
    return f" — {n}" if n else ""


def cmd_config(a):
    st = get_store()
    if a.setsmart_max_age_hours is not None:
        st.set("setsmart_max_age_hours", a.setsmart_max_age_hours)
        print(f"SetSmart lists must be at most {a.setsmart_max_age_hours} h old.")
    if a.drop_setsmart:
        st.set("setsmart_required", "0")
        st.set("setsmart_dropped_reason", a.drop_setsmart)
        st.event("setsmart_dropped", reason=a.drop_setsmart)
        print(f"SetSmart is no longer required. Reason recorded: {a.drop_setsmart}")
    if a.require_setsmart:
        st.set("setsmart_required", "1")
        st.event("setsmart_required")
        print("SetSmart lists are required again (24 h freshness).")
    return 0


